  static const double sm = 12;
  static const double base = 14;
  static const double md = 16;
  static const double lg = 18;
  static const double xl = 20;
  static const double xxl = 24;
  static const double xxxl = 30;
  static const double display = 36;
  static const double hero = 48;

  static const double caption = xs;
  static const double label = sm;
  static const double body = base;
  static const double bodyLarge = md;
  static const double subtitle = lg;
  static const double title = xl;
  static const double titleLarge = xxl;
  static const double headline = xxxl;
  static const double amount = hero;

  static const double trackingTight = -0.5;
  static const double trackingNormal = 0.0;
  static const double trackingWide = 0.4;
